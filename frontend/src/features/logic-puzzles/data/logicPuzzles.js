/** Puzzles per construct — used by the coverage test and by completion reporting. */
export const coverageByConstruct = (bank = logicPuzzles) =>
    CONSTRUCTS.reduce((acc, c) => ({ ...acc, [c]: bank.filter((p) => p.construct === c).length }), {});

/** Fisher-Yates, so a replay does not present the same order. */
export const shuffled = (bank = logicPuzzles) => {
    const out = [...bank];
    for (let i = out.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [out[i], out[j]] = [out[j], out[i]];
    }
    return out;
};
